// Generate lightweight circuit cards without building scenery. Usage: node tools/build-menu-cards.js
const fs = require('fs'), path = require('path'), THREE = require('../vendor/three/three.module.js');
require('../src/data/maps.js'); require('../src/engine/sim.js');
const cards = Object.fromEntries(MAPS.map(M => {
  const T = buildTrack(THREE, M), stride = Math.ceil(T.n / 96);
  return [M.id, { car: T.car.label, km: +(T.len / 1000).toFixed(1), points: T.S.filter((s, i) => i % stride === 0).map(s => [+s.x.toFixed(1) || 0, +s.z.toFixed(1) || 0]) }];
}));
fs.writeFileSync(path.join(__dirname, '../src/data/menu-cards.js'), '// Generated by node tools/build-menu-cards.js; menu selection never builds a track or scenery.\n(function (G) { G.MENU_CARDS = ' + JSON.stringify(cards) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n');
console.log('Generated cards for ' + MAPS.length + ' circuits');
